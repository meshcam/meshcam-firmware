"""Generate gateway/src/gw_secrets.h from secrets.ini — PlatformIO pre: extra_script.

WHY THIS EXISTS. secrets.ini's [secrets] build_flags used to be spliced
straight into ${gateway_common.flags}, so every compiler invocation carried the WiFi
PSKs, the live ingest token and the OTA password on its ARGV. Any user on the build
host could read them with ps, anything that snapshots a process list captured them,
and a compiler error that quotes the failing command echoes them into build logs and
session transcripts. That last one already happened on the leaf side (2026-08-09),
which is why the leaf moved to the gitignored header leaf/src/wire_secrets.h. This is
the same fix for the gateway: the header is the only new artifact, secrets.ini stays
the single source of truth, and nothing about the workflow changes.

The values are compiled into the binary either way — what this buys is keeping them
off the command line.

Also runnable by hand, which is how the leaf's wire_secrets.h gets regenerated:

    python3 gateway/gen_gw_secrets.py --out leaf/src/wire_secrets.h

(the leaf's copy still needs GW_INGEST_URL hand-edited afterwards — it points at the
local probe server, deliberately not at the real backend).
"""

import configparser
import os
import stat
import sys

# SCons exec()s extra_scripts without __file__, so the project dir has to come from
# PlatformIO when we are running as one.
if "Import" in globals():
    Import("env")               # noqa: F821  (PlatformIO construct)
    _PIO = True
    HERE = env.subst("$PROJECT_DIR")    # noqa: F821
else:
    _PIO = False
    HERE = os.path.dirname(os.path.abspath(__file__))

SECRETS_INI = os.path.join(HERE, "secrets.ini")
DEFAULT_OUT = os.path.join(HERE, "src", "gw_secrets.h")

HEADER = """\
// GENERATED by gateway/gen_gw_secrets.py from gateway/secrets.ini — do not edit.
// GITIGNORED (gateway/.gitignore). Never commit this file.
//
// Credentials live in a header rather than on the build command line: as -D flags they
// sit on every compiler invocation's ARGV, readable by any user via ps and captured by
// anything that snapshots a process list. A compiler error that quotes the failing
// command echoes them verbatim into build logs and session transcripts — that happened
// on the leaf side on 2026-08-09.
//
// Edit gateway/secrets.ini and rebuild; this file is regenerated on every build.
#pragma once

"""


def _unquote(s):
    """Strip ONE outer layer of ini quoting, the way PlatformIO does before handing the
    token to the compiler: '-DX="y"' -> -DX="y". The INNER quotes are part of the macro
    value and must survive, or a string macro stops being a C string literal."""
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "'\"":
        return s[1:-1]
    return s


def parse_flags(path):
    """Return [(macro, value_or_None)] from [secrets] build_flags in `path`."""
    if not os.path.isfile(path):
        sys.exit("gen_gw_secrets: %s not found — copy secrets.ini.example and fill it in"
                 % path)

    cp = configparser.ConfigParser(inline_comment_prefixes=None)
    cp.read(path, encoding="utf-8")
    if not cp.has_option("secrets", "build_flags"):
        sys.exit("gen_gw_secrets: %s has no [secrets] build_flags" % path)

    defines = []
    for raw in cp.get("secrets", "build_flags").splitlines():
        line = raw.strip()
        if not line or line.startswith(";") or line.startswith("#"):
            continue
        flag = _unquote(line)
        if not flag.startswith("-D"):
            sys.exit("gen_gw_secrets: %s: [secrets] build_flags takes only -D flags, got "
                     "a %r flag — put anything else in platformio.ini" % (path, flag[:2]))
        name, sep, value = flag[2:].partition("=")
        if not name.isidentifier():
            sys.exit("gen_gw_secrets: %s: %r is not a valid macro name" % (path, name))
        defines.append((name, value if sep else None))
    return defines


def render(defines):
    if not defines:
        sys.exit("gen_gw_secrets: [secrets] build_flags is empty")
    width = max(len(n) for n, _ in defines)
    body = "".join(
        "#define %-*s %s\n" % (width, name, value) if value is not None
        else "#define %s\n" % name
        for name, value in defines
    )
    return HEADER + body


def write_if_changed(path, text):
    """Only rewrite on a real change. An unconditional touch would recompile main.cpp
    — 2700 lines over the RNS templates — on every single build."""
    try:
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == text:
                os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)   # 0600
    return True


def main(out_path):
    changed = write_if_changed(out_path, render(parse_flags(SECRETS_INI)))
    # Print the path and nothing else. Echoing a value here would put the secrets
    # straight back into the build log, which is half of what this script exists to stop.
    print("[gen_gw_secrets] %s %s" % (os.path.relpath(out_path, HERE),
                                      "regenerated" if changed else "up to date"))


if _PIO:                        # running as a PlatformIO extra_script
    main(DEFAULT_OUT)
else:                           # running by hand
    _args = sys.argv[1:]
    if _args[:1] == ["--out"] and len(_args) == 2:
        main(os.path.abspath(_args[1]))
    elif _args:
        sys.exit("usage: gen_gw_secrets.py [--out PATH]")
    else:
        main(DEFAULT_OUT)
